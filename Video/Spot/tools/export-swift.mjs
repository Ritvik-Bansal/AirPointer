// Writes the AirPods model as Swift source, for the app.
//
//   node Video/Spot/tools/export-swift.mjs [App/UI/CaseModelData.swift]
//
// The app draws the case with SceneKit and has no bake step of its own, so the same solids
// the film is rendered from (web/src/model/airpods.js) are meshed here at a size that suits
// a small live view, packed tightly, and written out as a Swift file the app compiles in.
// Run it again whenever the model changes.
//
// Each vertex is ten bytes: its position as three 16-bit steps across the part's bounding
// box, its normal as three signed bytes, and one byte of tone. The tone is how much ambient
// light reaches the vertex, and on an AirPod it also carries the black windows, which the
// film paints with a shader and SceneKit takes as vertex colour.

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import { surfaceNets, ambient } from '../web/src/model/sdf.js'
import { PARTS, WINDOWS, DIM, SEAM, LIGHT, budMatrix } from '../web/src/model/airpods.js'

const here = path.dirname(fileURLToPath(import.meta.url))
const out = process.argv[2] || path.join(here, '../../../App/UI/CaseModelData.swift')

/// Grid spacing for each part, in millimetres.
// The body and the lid are finer than their size on screen needs, for the sake of one line:
// the rim where they meet. Coarser, it comes out ragged round the corners.
const CELL = { body: 0.4, lid: 0.4, hingeBody: 0.3, hingeLid: 0.3, lanyard: 0.2, port: 0.3, portCore: 0.3, bud: 0.3, tip: 0.4 }

/// How dark a window makes a vertex of an AirPod: 0 outside every window, 1 well inside one.
function windowCover(px, py, pz, nx, ny, nz) {
  let cover = 0
  for (const w of WINDOWS) {
    const qx = px - w.at[0], qy = py - w.at[1], qz = pz - w.at[2]
    const facing = nx * w.normal[0] + ny * w.normal[1] + nz * w.normal[2]
    const depth = qx * w.normal[0] + qy * w.normal[1] + qz * w.normal[2]
    if (facing < 0.2 || Math.abs(depth) > 5) continue
    const lu = qx * w.u[0] + qy * w.u[1] + qz * w.u[2]
    const lv = qx * w.v[0] + qy * w.v[1] + qz * w.v[2]
    const edge = (Math.hypot(lu / w.a, lv / w.b) - 1) * Math.min(w.a, w.b)
    cover = Math.max(cover, Math.min(Math.max(0.5 - edge / 0.3, 0), 1) * (w.finish === 'gloss' ? 1 : 0.9))
  }
  return cover
}

const chunks = []
const table = []
let offset = 0
let triangles = 0
for (const part of PARTS) {
  const mesh = surfaceNets(part.field, part.bounds, CELL[part.name])
  if (mesh.holes) throw new Error(`${part.name}: the mesh has ${mesh.holes} holes`)
  const ao = ambient(mesh.positions, mesh.normals, part.occluder)
  const count = mesh.positions.length / 3
  const low = [Infinity, Infinity, Infinity], high = [-Infinity, -Infinity, -Infinity]
  for (let v = 0; v < count; v++) for (let a = 0; a < 3; a++) {
    low[a] = Math.min(low[a], mesh.positions[v * 3 + a])
    high[a] = Math.max(high[a], mesh.positions[v * 3 + a])
  }
  const vertices = Buffer.alloc(count * 10)
  for (let v = 0; v < count; v++) {
    for (let a = 0; a < 3; a++) {
      const step = Math.round((mesh.positions[v * 3 + a] - low[a]) / (high[a] - low[a]) * 65535)
      vertices.writeUInt16LE(step, v * 10 + a * 2)
      vertices.writeInt8(Math.round(mesh.normals[v * 3 + a] * 127), v * 10 + 6 + a)
    }
    // Ambient light is taken most of the way, not all of it: the app lights the case
    // brightly and evenly, and a crevice should read as shaded, not as a black line.
    let tone = 1 - 0.8 * (1 - ao[v] / 255)
    if (part.name === 'bud') {
      const p = mesh.positions, n = mesh.normals
      tone *= 1 - 0.96 * windowCover(p[v * 3], p[v * 3 + 1], p[v * 3 + 2], n[v * 3], n[v * 3 + 1], n[v * 3 + 2])
    }
    vertices.writeUInt8(Math.round(tone * 255), v * 10 + 9)
  }
  const wide = count > 65535
  const indices = Buffer.alloc(mesh.indices.length * (wide ? 4 : 2))
  mesh.indices.forEach((index, i) => (wide ? indices.writeUInt32LE(index, i * 4) : indices.writeUInt16LE(index, i * 2)))
  chunks.push(vertices, indices)
  table.push({ name: part.name, vertices: count, indices: mesh.indices.length, wide, low, high, offset })
  offset += vertices.length + indices.length
  triangles += mesh.indices.length / 3
  console.log(`${part.name.padEnd(10)} ${String(count).padStart(6)} vertices ${String(mesh.indices.length / 3).padStart(7)} triangles`)
}

const base64 = Buffer.concat(chunks).toString('base64')
const lines = []
for (let i = 0; i < base64.length; i += 16000) lines.push(`        "${base64.slice(i, i + 16000)}",`)
const f = n => (Number.isInteger(n) ? n.toFixed(1) : String(Number(n.toFixed(5))))
const vec = a => `SIMD3<Float>(${a.map(f).join(', ')})`
const m = budMatrix()

writeFileSync(out, `// Generated by Video/Spot/tools/export-swift.mjs from Video/Spot/web/src/model/airpods.js.
// Do not edit by hand: change the model and run the tool again.

import simd

/// The AirPods Pro 3 case and one AirPod, as packed meshes. Millimetres; x to the right as
/// you face the front of the case, y up, z out of the front toward you; the origin is the
/// middle of the closed case. CaseModel.swift unpacks them.
enum CaseModelData {
    struct Part {
        let name: String
        let vertices: Int
        /// Three for every triangle.
        let indices: Int
        /// Whether an index is four bytes rather than two.
        let wide: Bool
        /// The part's bounding box, which its packed positions are steps across.
        let low: SIMD3<Float>
        let high: SIMD3<Float>
        /// Where the part starts in the packed bytes.
        let offset: Int
    }

    static let parts: [Part] = [
${table.map(p => `        Part(name: "${p.name}", vertices: ${p.vertices}, indices: ${p.indices}, wide: ${p.wide}, low: ${vec(p.low)}, high: ${vec(p.high)}, offset: ${p.offset}),`).join('\n')}
    ]

    /// Half the case's width, height and depth.
    static let half = ${vec([DIM.W, DIM.H, DIM.D])}
    /// Height of the line where the lid meets the body. The lid turns about this line on the back face.
    static let seam: Float = ${f(SEAM)}
    /// The status light, on the front face.
    static let light = ${vec([LIGHT.x, LIGHT.y, LIGHT.z])}
    /// Where the left AirPod sits in the case, as the columns of a transform from its own
    /// axes. The right one is its mirror image.
    static let pod = simd_float4x4(columns: (
        SIMD4<Float>(${m.slice(0, 4).map(f).join(', ')}),
        SIMD4<Float>(${m.slice(4, 8).map(f).join(', ')}),
        SIMD4<Float>(${m.slice(8, 12).map(f).join(', ')}),
        SIMD4<Float>(${m.slice(12, 16).map(f).join(', ')})
    ))

    /// The packed meshes, base64, in pieces (one long literal is slow to compile).
    static let packed: [String] = [
${lines.join('\n')}
    ]
}
`)
console.log(`${triangles} triangles, ${(offset / 1e6).toFixed(2)} MB packed, written to ${path.relative(process.cwd(), out)}`)
